#!/usr/bin/env python3
"""COMPILER-IR-013: adversarial native re-entrant Minecraft queue ordering.

A test-only ServerScoreboard.onScoreChanged callback queues a REAL function
via ExecutionContext.queueInitialFunctionCall, rather than synchronously
mutating the observed score. Vanilla must run the newly staged function before
the next function command. Existing IR-008/012 action batching can miss that
boundary; IR-013's guarded bytecode/interpreter yields to a vanilla-command
tail after observing queueNext generation change.

Arms: native, unsafe compiled ASM, safe compiled ASM, safe interpreter, unsafe
direct function scheduler, and safe direct scheduler. The two unsafe modes
are required negative controls; parity with vanilla is required for every
safe arm, including exact partial scores at low command quotas.

This is a correctness gate, not a CPU benchmark or production promotion.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import secrets
import shutil
import subprocess

from ci_smoke_server import ROOT, RUNS, unused_port, wait_for_rcon

OUT = ROOT / "build/reports/COMPILER-IR-013"
PACK = "fc_typed_ir013"
OBJ = "fc_ir"
ADD = "scoreboard players add #x fc_ir 1"
TRIGGER = "scoreboard players set #ir013_trigger fc_ir 1"
OBSERVE = "scoreboard players operation #ir013_seen fc_ir = #ir013_mark fc_ir"
QUOTAS = (1, 2, 3, 4, 5, 8, 16, 31, 32, 33, 64, 65, 70, 130, 260)
MODES = (
    "native",
    "bytecode_unsafe",
    "bytecode_guarded",
    "interpreted_guarded",
    "direct_unsafe",
    "direct_guarded",
)

FUNCTIONS = {
    # The one-scoreboard callback queues these two vanilla effects through
    # a real CallFunction. Before it runs, #mark and #count are both zero.
    "ir013_injected": [
        "scoreboard players add #ir013_mark fc_ir 7",
        "scoreboard players add #ir013_count fc_ir 1",
    ],
    "ir013_short": [
        TRIGGER, OBSERVE, "scoreboard players add #ir013_seen fc_ir 1",
    ],
    "ir013_middle": [
        *([ADD] * 6), TRIGGER, OBSERVE,
        "scoreboard players add #ir013_seen fc_ir 1",
        *([ADD] * 7),
    ],
    # Reentrant callback at instruction 31, inside the first 64-command
    # generated bytecode region. This is the primary negative control.
    "ir013_inside128": [ADD] * 30 + [TRIGGER, OBSERVE] + [ADD] * 96,
    # Identical injected action at the LAST command of a generated region.
    # Even unsafe IR should naturally reach the queue boundary here.
    "ir013_boundary128": [ADD] * 63 + [TRIGGER, OBSERVE] + [ADD] * 63,
    "ir013_twice": [
        TRIGGER,
        OBSERVE,
        "scoreboard players add #ir013_trigger fc_ir 1",
        "scoreboard players operation #ir013_seen2 fc_ir = #ir013_mark fc_ir",
        ADD,
    ],
    "ir013_guarded": [
        TRIGGER,
        "execute if score #ir013_mark fc_ir matches 7 run "
        "scoreboard players add #ir013_seen fc_ir 5",
        "scoreboard players add #ir013_seen fc_ir 1",
    ],
    # Explicit vanilla scheduling barrier: any compilation must preserve
    # all of the uncompiled function's call placement and callback effects.
    "ir013_barrier": [
        "scoreboard players set #x fc_ir 1",
        TRIGGER,
        "function fc_ir:ir013_helper",
        OBSERVE,
        "scoreboard players add #ir013_seen fc_ir 1",
    ],
    "ir013_helper": ["scoreboard players add #x fc_ir 2"],
}
EXPECTED = {
    "ir013_short": {"mark": 7, "count": 1, "seen": 8, "trigger": 1},
    "ir013_middle": {"x": 13, "mark": 7, "count": 1, "seen": 8},
    "ir013_inside128": {"x": 126, "mark": 7, "count": 1, "seen": 7},
    "ir013_boundary128": {"x": 126, "mark": 7, "count": 1, "seen": 7},
    "ir013_twice": {"x": 1, "mark": 14, "count": 2, "seen": 7,
                    "seen2": 14, "trigger": 2},
    "ir013_guarded": {"mark": 7, "count": 1, "seen": 6},
    "ir013_barrier": {"x": 3, "mark": 7, "count": 1, "seen": 8},
}
HOLDERS = {
    "x": "#x", "mark": "#ir013_mark", "seen": "#ir013_seen",
    "seen2": "#ir013_seen2", "count": "#ir013_count",
    "trigger": "#ir013_trigger", "result": "#result",
}


def fixture(work: Path) -> None:
    root = work / "world/datapacks" / PACK
    funcs = root / "data/fc_ir/function"
    funcs.mkdir(parents=True, exist_ok=True)
    (root / "pack.mcmeta").write_text(json.dumps({
        "pack": {"description": "IR013 original callback queue parity fixture",
                 "min_format": [97, 1], "max_format": [97, 1]}
    }) + "\n", encoding="utf-8")
    for name, lines in FUNCTIONS.items():
        (funcs / (name + ".mcfunction")).write_text(
            "\n".join(lines) + "\n", encoding="utf-8")


def options(mode: str) -> dict[str, str]:
    if mode not in MODES:
        raise ValueError(mode)
    wrapped = mode != "native"
    guarded = mode.endswith("_guarded")
    interpreted = mode == "interpreted_guarded"
    return {
        "FC_WRAPPER_PROBE": str(wrapped).lower(),
        "FC_TYPED_IR_MODE": ("interpreted" if interpreted else "bytecode") if wrapped else "",
        "FC_TYPED_IR_NAMESPACE": "fc_ir" if wrapped else "",
        "FC_TYPED_IR_DIRECT_FUNCTION": "true",
        "FC_TYPED_IR_DIRECT_FUNCTION_TOGGLE": "true",
        "FC_TYPED_IR_DIRECT_FUNCTION_HARNESS": "true",
        "FC_TYPED_IR_DIAGNOSTICS": "true",
        "FC_TYPED_IR_REENTRANT_TEST_OBSERVER": "true",
        "FC_TYPED_IR_REENTRANT_SAFE": str(guarded).lower(),
        "FC_TYPED_IR_SCORE_CACHE": "false",
        "FC_TYPED_IR_SINGLETON_FEEDBACK": "false",
        "FC_DIRECT_SCHEDULER_PROTOTYPE": "false",
        "FC_FUSED_REGION_PROTOTYPE": "false",
        "FC_SCORE_ADD_PROTOTYPE": "false",
        "FC_BYTECODE_REGION_PROTOTYPE": "false",
        "FC_SCHED_ARCH_COUNTERS": "false",
        "FC_COMMAND_CALLBACK_METRICS": "false",
        "FC_SCORE_ADD_METRICS": "false",
        "FC_SCORE_ADD_TIMING": "false",
        "FC_RUNTIME_TRACE": "false",
    }


def start(mode: str):
    RUNS.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    work = RUNS / f"ci-ir013-{mode}"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    fixture(work)
    (work / "eula.txt").write_text("eula=true\n", encoding="utf-8")
    port, rcon_port = unused_port(), unused_port()
    passwd = secrets.token_hex(18)
    (work / "server.properties").write_text("\n".join((
        "online-mode=false", "enable-rcon=true",
        "broadcast-rcon-to-ops=false", "level-name=world",
        "level-type=minecraft:flat", "pause-when-empty-seconds=-1",
        "view-distance=2", "simulation-distance=2",
        "max-tick-time=-1", "max-players=1",
        f"server-port={port}", f"rcon.port={rcon_port}",
        f"rcon.password={passwd}",
    )) + "\n", encoding="utf-8")
    env = dict(os.environ)
    env.update(options(mode))
    cmd = [
        str(ROOT / "gradlew"), "--no-daemon",
        "-Dorg.gradle.jvmargs=-Xmx1G -Dfile.encoding=UTF-8",
        "-PfcJvmArgs=-Xms512M,-Xmx2G",
        f"-PfcRunDirectory={work.relative_to(ROOT)}", "runServer",
    ]
    log = (OUT / (mode + ".server.log")).open("w", encoding="utf-8")
    process = subprocess.Popen(cmd, cwd=ROOT, env=env, stdout=log,
                               stderr=subprocess.STDOUT, stdin=subprocess.PIPE)
    try:
        client = wait_for_rcon(process, rcon_port, passwd, timeout_seconds=240)
        if PACK not in client.command("datapack list enabled"):
            raise AssertionError(f"{mode}: fixture disabled")
        client.command("scoreboard objectives add fc_ir dummy")
        client.command("gamerule minecraft:max_command_sequence_length 65536")
        client.command("gamerule sendCommandFeedback false")
        return process, client, log
    except BaseException:
        process.terminate()
        process.wait(timeout=40)
        log.close()
        raise


def stop(process, client, log) -> None:
    try:
        client.command("stop")
    except (RuntimeError, OSError):
        pass
    client.close()
    try:
        process.wait(timeout=40)
    except subprocess.TimeoutExpired:
        process.terminate()
        process.wait(timeout=15)
    log.close()


def scalar(client, holder: str) -> int | None:
    response = client.command(f"scoreboard players get {holder} fc_ir")
    match = re.search(r"has (-?\d+)", response)
    if match:
        return int(match.group(1))
    if "none is set" in response:
        return None
    raise AssertionError(f"Unknown score response for {holder}: {response!r}")


def snapshot(client) -> dict:
    return {name: scalar(client, holder) for name, holder in HOLDERS.items()}


def reset(client) -> None:
    # CRITICAL: the callback is on onScoreChanged(#ir013_trigger), so use
    # reset/removal and NEVER set its row to zero in an RCON command.
    client.command("scoreboard players reset #ir013_trigger fc_ir")
    for name, holder in HOLDERS.items():
        if name != "trigger":
            client.command(f"scoreboard players set {holder} fc_ir 0")


def invoke(client, name: str, empty_callback: bool = True) -> None:
    cmd = ("fc_ir013_call " if empty_callback else "function ") + "fc_ir:" + name
    response = client.command(cmd)
    expected = "FC_ARCH_CALL queued " if empty_callback else "Running function "
    if not response.startswith(expected):
        raise AssertionError(f"Failed to call {name}: {response!r}")


def stat(response: str, key: str) -> int:
    match = re.search(rf"\b{re.escape(key)}=(\d+)", response)
    if not match:
        raise AssertionError(f"No counter {key}: {response!r}")
    return int(match.group(1))


def run_arm(mode: str) -> dict:
    process, client, log = start(mode)
    report = {"mode": mode, "status": "started", "cases": {},
              "compiler_status": None, "observer_status": None}
    try:
        if mode in ("bytecode_unsafe", "bytecode_guarded", "interpreted_guarded"):
            # Normal child-frame/ContinuationTask compiler path.
            response = client.command("fc_ir012_direct off")
            if "enabled=false" not in response:
                raise AssertionError(f"Couldn't disable IR-012 direct: {response!r}")
        for name, expected in EXPECTED.items():
            reset(client)
            invoke(client, name)
            state = snapshot(client)
            report["cases"][name] = state
            if mode == "native" or mode.endswith("_guarded"):
                for field, value in expected.items():
                    if state[field] != value:
                        raise AssertionError(f"{mode}/{name}/{field} "
                                             f"got {state[field]} expected {value}")

        # Public function-callback path and nested-function barriers must
        # remain original. Their observed effects are still compared.
        reset(client)
        invoke(client, "ir013_short", empty_callback=False)
        report["cases"]["public_function"] = snapshot(client)

        # Execute-store function return callback still stays vanilla and
        # must not be affected by yielding compiled command tails.
        reset(client)
        client.command("execute store result score #result fc_ir "
                       "run function fc_ir:ir013_short")
        report["cases"]["stored_result"] = snapshot(client)

        # Debug traces force original CallFunction; the ORIGINAL function
        # size must be reported rather than a collapsed chunk count.
        reset(client)
        debug = client.command("debug function fc_ir:ir013_inside128")
        if "trace" not in debug.lower():
            raise AssertionError(f"{mode}: trace not activated {debug!r}")
        report["cases"]["debug_traced"] = snapshot(client)
        report["debug_reply"] = debug

        for quota in QUOTAS:
            for name in ("ir013_short", "ir013_inside128", "ir013_boundary128",
                         "ir013_twice", "ir013_guarded"):
                client.command("gamerule minecraft:max_command_sequence_length 65536")
                reset(client)
                client.command(f"gamerule minecraft:max_command_sequence_length {quota}")
                reply = client.command("gamerule minecraft:max_command_sequence_length")
                numbers = re.findall(r"\d+", reply)
                if not numbers or int(numbers[-1]) != quota:
                    raise AssertionError(f"{mode}: quota readback failed {reply!r}")
                invoke(client, name)
                client.command("gamerule minecraft:max_command_sequence_length 65536")
                report["cases"][f"{name}_quota_{quota}"] = snapshot(client)

        report["compiler_status"] = client.command("functioncompiler ir008")
        report["observer_status"] = client.command("fc_ir013_status")
        if stat(report["observer_status"], "reentrant_test_injections") <= 0:
            raise AssertionError(f"No real callback function enqueued: {report}")
        if mode != "native":
            if stat(report["compiler_status"], "compiled_regions") <= 0:
                raise AssertionError(f"Compiler not activated: {report}")
            if mode != "interpreted_guarded" and stat(
                    report["compiler_status"], "bytecode_regions") <= 0:
                raise AssertionError(f"ASM not emitted: {report}")
        if mode.endswith("_guarded"):
            if stat(report["compiler_status"], "reentrant_yields") <= 0:
                raise AssertionError(f"No detected queue interleaving: {report}")
            if stat(report["compiler_status"], "reentrant_queued_steps") <= 0:
                raise AssertionError(f"No resumed original commands: {report}")
        if mode.startswith("direct"):
            if stat(report["compiler_status"], "direct_function_executed") <= 0:
                raise AssertionError(f"Direct scheduling didn't run: {report}")
        report["status"] = "accepted"
        print("IR013_NATIVE_ARM " + json.dumps({
            "mode": mode, "cases": len(report["cases"]),
            "compiler_status": report["compiler_status"],
            "observer_status": report["observer_status"]
        }, sort_keys=True), flush=True)
        return report
    except BaseException as error:
        report["status"] = "invalid"
        report["error"] = repr(error)
        raise
    finally:
        stop(process, client, log)
        (OUT / f"{mode}.json").write_text(json.dumps(report, indent=2) + "\n")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    report = {"milestone": "COMPILER-IR-013", "status": "started", "arms": []}
    try:
        for mode in MODES:
            report["arms"].append(run_arm(mode))
            (OUT / "results.json").write_text(json.dumps(report, indent=2) + "\n")
        vanilla = report["arms"][0]["cases"]
        differences = {}
        for arm in report["arms"][1:]:
            changed = {name: {"vanilla": state, "actual": arm["cases"][name]}
                       for name, state in vanilla.items()
                       if state != arm["cases"][name]}
            differences[arm["mode"]] = changed
            if arm["mode"].endswith("_guarded") and changed:
                raise AssertionError(
                    f"IR013 GUARDED NATIVE PARITY FAILURE {arm['mode']}: "
                    f"{list(changed)[:8]}")
        for mode in ("bytecode_unsafe", "direct_unsafe"):
            if "ir013_inside128" not in differences[mode]:
                raise AssertionError(
                    f"Unsafe negative control did not expose inside-chunk "
                    f"interleaving regression: {mode}")
            if "ir013_boundary128" in differences[mode]:
                raise AssertionError(
                    f"Boundary negative control unexpectedly diverged: {mode}")
        report["status"] = "accepted"
        report["native_guarded_parity"] = True
        report["unsafe_negative_control_diverged"] = True
        report["case_count"] = len(vanilla)
        report["mismatches"] = {mode: list(changed)
                                for mode, changed in differences.items()}
        report["production_promotion"] = False
    except BaseException as error:
        report["status"] = "invalid"
        report["error"] = repr(error)
        raise
    finally:
        (OUT / "results.json").write_text(json.dumps(report, indent=2) + "\n")
    print("IR013_SUMMARY " + json.dumps({
        "status": report["status"], "modes": list(MODES),
        "cases_per_mode": report["case_count"],
        "unsafe_negative_control_diverged": True,
        "guarded_native_parity": True,
        "production_promotion": False,
        "differences": report["mismatches"]
    }, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
