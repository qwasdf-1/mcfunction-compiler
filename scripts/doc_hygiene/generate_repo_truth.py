#!/usr/bin/env python3
"""Generate repo-grounded documentation aids for Function Compiler."""

from __future__ import annotations

import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

try:
    from scripts.doc_hygiene.doc_links import documentation_path_check
    from scripts.doc_hygiene.repo_inventory import (
        FileEntry,
        ROOT_DOCS,
        iter_repo_files,
        rel,
    )
except ModuleNotFoundError:
    from doc_links import documentation_path_check
    from repo_inventory import FileEntry, ROOT_DOCS, iter_repo_files, rel


REPO = Path(__file__).resolve().parents[2]
DOCS = REPO / "docs"
SRC = REPO / "src"

ACTIVE_DOC_EXCLUDED_DIRS = {"archive", "generated"}

JAVA_CLASS = re.compile(
    r"^\s*(?:public|protected|private)?\s*(?:static|final|abstract)?\s*(?:class|interface|record|enum)\s+([A-Za-z0-9_]+)"
)
JAVA_MIXIN = re.compile(r"^\s*@Mixin\(([^)]+)\)")
JAVA_METHOD = re.compile(
    r"^\s*(?:public|protected)\s+(?:static\s+)?[A-Za-z0-9_<>\[\],\s]+\s+([a-z][A-Za-z0-9_]+)\s*\("
)
PY_DEF = re.compile(r"^\s*(?:async\s+)?def\s+([A-Za-z0-9_]+)\s*\(")
PY_CLASS = re.compile(r"^\s*class\s+([A-Za-z0-9_]+)")


def symbol_for_line(kind: str, line: str) -> str | None:
    if kind == "java":
        m_mixin = JAVA_MIXIN.match(line)
        if m_mixin:
            target = m_mixin.group(1).replace(".class", "").strip().split(".")[-1]
            return f"@Mixin({target})"
        m_cls = JAVA_CLASS.match(line)
        if m_cls:
            return f"class {m_cls.group(1)}"
        m_meth = JAVA_METHOD.match(line)
        if m_meth:
            return f"method {m_meth.group(1)}()"
    elif kind == "py":
        m_cls = PY_CLASS.match(line)
        if m_cls:
            return f"class {m_cls.group(1)}"
        m_def = PY_DEF.match(line)
        if m_def:
            return f"def {m_def.group(1)}()"
    return None


def collect_symbols(entries: list[FileEntry]) -> dict[str, list[str]]:
    symbols_by_file: dict[str, list[str]] = defaultdict(list)
    for entry in entries:
        if entry.kind not in {"java", "py"}:
            continue
        try:
            lines = entry.path.read_text(encoding="utf-8", errors="ignore").splitlines()
        except OSError:
            continue
        for line_no, line in enumerate(lines, start=1):
            sym = symbol_for_line(entry.kind, line)
            if sym and len(symbols_by_file[rel(REPO, entry.path)]) < 12:
                symbols_by_file[rel(REPO, entry.path)].append(f"`{sym}`:{line_no}")
    return symbols_by_file


def build_repo_structure(entries: list[FileEntry]) -> str:
    by_dir: dict[str, list[str]] = defaultdict(list)
    top_counts: Counter[str] = Counter()
    by_kind: Counter[str] = Counter()

    for entry in entries:
        r_path = rel(REPO, entry.path)
        top = r_path.split("/", 1)[0]
        top_counts[top] += 1
        by_kind[entry.kind] += 1
        parent = entry.path.parent.relative_to(REPO).as_posix()
        by_dir[parent].append(entry.path.name)

    lines = [
        "# Repository Structure",
        "",
        "_Generated by `scripts/doc_hygiene/generate_repo_truth.py`._",
        "",
        "## Top-Level File Inventory",
        "",
    ]
    for top, count in sorted(top_counts.items()):
        lines.append(f"- `{top}/`: {count} indexed files")

    lines.extend([
        "",
        "## File Kinds",
        "",
        ", ".join(f"`.{kind}`={count}" for kind, count in sorted(by_kind.items())),
        "",
        "## Directory Tree Overview",
        "",
    ])

    for top in sorted(top_counts.keys()):
        lines.append(f"### `{top}/`")
        dirs = sorted(k for k in by_dir if k == top or k.startswith(f"{top}/"))
        for d in dirs:
            depth = d.count("/")
            if depth > 3:
                continue
            indent = "  " * depth
            files = by_dir[d]
            summary = ", ".join(f"`{f}`" for f in files[:4])
            if len(files) > 4:
                summary += f", ... +{len(files) - 4} more"
            lines.append(f"- {indent}`{d}/`: {summary}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def build_repo_navigation_index(entries: list[FileEntry]) -> str:
    symbols_by_file = collect_symbols(entries)

    lines = [
        "# Repository Navigation Index",
        "",
        "_Generated by `scripts/doc_hygiene/generate_repo_truth.py`._",
        "",
        "This navigation index summarizes key code symbols across Java source and Python tooling.",
        "",
        "## Core Java Components (`src/main/java`)",
        "",
    ]

    java_paths = sorted(p for p in symbols_by_file if p.startswith("src/main/java"))
    for p in java_paths:
        syms = symbols_by_file[p]
        lines.append(f"- [`{p}`](../../{p}):")
        for s in syms:
            lines.append(f"  - {s}")

    lines.extend([
        "",
        "## Key Tooling Scripts (`scripts/`)",
        "",
    ])
    py_paths = sorted(p for p in symbols_by_file if p.startswith("scripts/"))
    for p in py_paths:
        syms = symbols_by_file[p]
        lines.append(f"- [`{p}`](../../{p}):")
        for s in syms[:8]:
            lines.append(f"  - {s}")

    return "\n".join(lines).rstrip() + "\n"


def build_feature_doc_index() -> str:
    feature_dir = DOCS / "reference" / "features"
    lines = [
        "# Feature Documentation Index",
        "",
        "_Generated by `scripts/doc_hygiene/generate_repo_truth.py`._",
        "",
        "This index maps curated feature documentation to status and component owners.",
        "",
        "| Document | Status | Description |",
        "|---|---|---|",
    ]

    if feature_dir.exists():
        for path in sorted(feature_dir.glob("*.md")):
            if path.name in {"README.md", "inventory.md"}:
                continue
            content = path.read_text(encoding="utf-8", errors="ignore")
            title = path.stem.replace("-", " ").title()
            for line in content.splitlines():
                if line.startswith("# "):
                    title = line.lstrip("# ").strip()
                    break

            status = "Maintained"
            for line in content.splitlines()[:15]:
                if line.startswith("**Status:**"):
                    status = line.split(":", 1)[1].strip().strip("*").strip()
                    break

            lines.append(f"| [`{path.name}`](../reference/features/{path.name}) | {status} | {title} |")

    lines.extend([
        "",
        "## Repo-Wide Inventory",
        "",
        "- Full feature inventory: [`docs/reference/features/inventory.md`](../reference/features/inventory.md)",
    ])
    return "\n".join(lines).rstrip() + "\n"


def parse_test_matrix_summary() -> tuple[int, int, int]:
    matrix_path = DOCS / "v1" / "plans" / "minecraft-function-compiler-test-matrix-v0.1.csv"
    if not matrix_path.exists():
        return 0, 0, 0
    total = 0
    p0 = 0
    p1 = 0
    with open(matrix_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            total += 1
            priority = row.get("priority", "").upper()
            if priority == "P0":
                p0 += 1
            elif priority == "P1":
                p1 += 1
    return total, p0, p1


def build_documentation_index() -> str:
    checked_refs, unresolved_refs = documentation_path_check(
        REPO, DOCS, ROOT_DOCS, ACTIVE_DOC_EXCLUDED_DIRS
    )
    total_cases, p0_cases, p1_cases = parse_test_matrix_summary()

    lines = [
        "# Documentation Index",
        "",
        "_Generated by `scripts/doc_hygiene/generate_repo_truth.py`._",
        "",
        "## Active Authority Documents",
        "",
        "| Layer | File | Purpose |",
        "|---|---|---|",
        "| Top-Level Reference | [`docs/project-reference.md`](../project-reference.md) | Project scope, evidence rules, and source map. |",
        "| Current State | [`docs/current-state.md`](../current-state.md) | Present-tense verified implementation and test matrix status. |",
        "| Architecture | [`docs/architecture.md`](../architecture.md) | Runtime ownership model, execution path, and Mixin contracts. |",
        "| Architecture Decisions | [`docs/architecture-decisions.md`](../architecture-decisions.md) | Durable architecture decision records and status. |",
        "| Verification Workflow | [`docs/verification.md`](../verification.md) | Evidence loop, target toolchain, and parity gates. |",
        "| Benchmarking Protocol | [`docs/benchmarking.md`](../benchmarking.md) | Workload qualification, timing protocol, and reporting contract. |",
        "| Documentation Layout | [`docs/documentation-layout.md`](../documentation-layout.md) | Canonical documentation taxonomy and lifecycle rules. |",
        "",
        "## Validation Matrix Summary",
        "",
        f"- Total test cases: {total_cases}",
        f"- P0 semantic cases: {p0_cases}",
        f"- P1 benchmark cases: {p1_cases}",
        "- Active matrix location: [`docs/v1/plans/minecraft-function-compiler-test-matrix-v0.1.csv`](../v1/plans/minecraft-function-compiler-test-matrix-v0.1.csv)",
        "",
        "## Documentation Health & References",
        "",
        f"- Total internal path references verified: {checked_refs}",
        f"- Unresolved references: {len(unresolved_refs)}",
        "",
    ]

    if unresolved_refs:
        lines.append("### Unresolved References Requiring Review")
        lines.append("")
        for doc, line_no, raw in unresolved_refs[:20]:
            lines.append(f"- `{doc}:{line_no}`: `{raw}`")
        lines.append("")
    else:
        lines.append("All checked documentation references resolved successfully.")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    generated_dir = DOCS / "generated"
    generated_dir.mkdir(parents=True, exist_ok=True)

    entries = iter_repo_files(REPO)
    (generated_dir / "repo-structure.md").write_text(
        build_repo_structure(entries), encoding="utf-8"
    )
    (generated_dir / "repo-navigation-index.md").write_text(
        build_repo_navigation_index(entries), encoding="utf-8"
    )
    (generated_dir / "feature-doc-index.md").write_text(
        build_feature_doc_index(), encoding="utf-8"
    )
    (generated_dir / "documentation-index.md").write_text(
        build_documentation_index(), encoding="utf-8"
    )
    print(f"Generated ground-truth documentation for {len(entries)} indexed files.")


if __name__ == "__main__":
    main()
